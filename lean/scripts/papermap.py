# py-rules-ok: text-editing glue, rebuilds the paper-to-Lean index with per-paper files and qualified names
"""Usage: python3 -u papermap.py   (run in ~/virasoro) writes lean/PAPER_MAP.md and lean/scratch/CheckMAPmain.lean."""
import re, os, glob, sys
if '-h' in sys.argv or '--help' in sys.argv:
    print(__doc__); sys.exit(0)

def auxnums(f):
    d = {}
    for m in re.finditer(r'\\newlabel\{([^}]*)\}\{\{([^}]*)\}', open(f).read()):
        d[m.group(1)] = m.group(2)
    return d

def envs(f):
    s = open(f).read(); out = []
    for m in re.finditer(r'\\begin\{(theorem|lemma|proposition|corollary|definition)\}(\[[^\]]*\])?(.*?)\\end\{\1\}', s, re.S):
        lab = re.search(r'\\label\{([^}]*)\}', m.group(0))
        if lab:
            out.append((m.group(1), lab.group(1)))
    return out

def ns_at(s, pos):
    stack = []
    for m in re.finditer(r'^(namespace|end|section)\s*([A-Za-z0-9_.]*)', s[:pos], re.M):
        if m.group(1) == 'namespace':
            stack.append(('ns', m.group(2)))
        elif m.group(1) == 'section':
            stack.append(('sec', m.group(2)))
        elif stack:
            stack.pop()
    return '.'.join(x[1] for x in stack if x[0] == 'ns')

def scan():
    lab2thm, stmts = {}, {}
    for f in glob.glob('lean/Virasoro/**/*.lean', recursive=True):
        s = open(f).read()
        rel = os.path.relpath(f, 'lean')
        for m in re.finditer(r'Paper label:\s*([a-zA-Z]+:[A-Za-z0-9-]+)\s*-/\s*(?:@\[[^\]]*\]\s*)?(?:theorem|lemma)\s+([A-Za-z0-9_\.\']+)', s):
            lab2thm.setdefault(m.group(1), set()).add((ns_at(s, m.start(2)) + '.' + m.group(2), rel))
        for m in re.finditer(r'^(?:def|abbrev) (Stmt_[A-Za-z0-9_]+)', s, re.M):
            stmts.setdefault(m.group(1), []).append(rel)
    return lab2thm, stmts

