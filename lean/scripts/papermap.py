def rows_for(title, tex, aux, side, lab2thm, stmts, names):
    nums = auxnums(aux)
    out = [f"## {title}", "",
           "| Paper | Label | Lean statement | Labelled theorem (file) |", "|---|---|---|---|"]
    for kind, lab in envs(tex):
        paper = side(lab)
        lean_lab = lab[:-4] if lab.endswith('-sph') else lab
        num = nums.get(lab, '?')
        base = 'Stmt_' + lean_lab.replace(':', '_').replace('-', '_')
        st = '—'
        for c in (base + '_rev26', base + '_rev25', base + '_paper', base):
            if any(('Sphere' in f) == (paper == 'sphere') for f in stmts.get(c, [])):
                st = c
                break
        if kind == 'definition' and st == '—':
            out.append(f"| {KIND[kind]} {num} | `{lab}` | definitions: {DEFS.get(lean_lab, '')} | — |")
            continue
        ths = [t for t in lab2thm.get(lean_lab, set()) if ('/Sphere/' in t[1]) == (paper == 'sphere')]
        if (paper, lean_lab) in MANUAL:
            ths = [MANUAL[(paper, lean_lab)]]
        if st.endswith('_rev26'):
            ths = [t for t in ths if 'Rev20261126' in t[1]]
        elif st.endswith('_rev25'):
            ths = [t for t in ths if 'Rev20261125' in t[1]]
        elif st.endswith('_paper') or st in ('Stmt_lem_ward_induction', 'Stmt_prop_gaussian_limit'):
            ths = [t for t in ths if 'Rev20261124' in t[1]]
        ths = sorted(set(ths))
        names.extend(t[0] for t in ths)
        out.append(f"| {KIND[kind]} {num} | `{lab}` | `{st}` | " + '; '.join(f"`{t[0]}` ({t[1]})" for t in ths) + " |")
    out.append("")
    return out

def main():
    lab2thm, stmts = scan()
    names, out = [], list(HEAD)
    out += rows_for('sphere/paper.tex (large-weight limit)', 'sphere/paper.tex', 'sphere/paper.aux',
                    lambda lab: 'sphere', lab2thm, stmts, names)
    out += rows_for('paper.tex (colliding poles: Part I torus, Part II sphere)', 'paper.tex', 'paper.aux',
                    lambda lab: 'sphere' if lab in SPHERE_IN_B else 'torus', lab2thm, stmts, names)
    out += rows_for('irreducible/paper.tex (irreducible traces)', 'irreducible/paper.tex', 'irreducible/paper.aux',
                    lambda lab: 'torus', lab2thm, stmts, names)
    open('lean/PAPER_MAP.md', 'w').write('\n'.join(out) + '\n')
    names = list(dict.fromkeys(names))
    open('lean/scratch/CheckMAPmain.lean', 'w').write('import Virasoro\n\n' + '\n'.join(f'#print axioms {n}' for n in names) + '\n')
    print(len(names), 'theorems')

main()
