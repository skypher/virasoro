"""Generate the Lean evaluation lemmas for the Theta identity of one level (7 or 10).

Usage: python3 -u gen_lean.py LEVEL OUT.lean [-h|--help]

For each of the four labels of the level-LEVEL diamond it writes: the genAIndex set and the
non-degeneracy 4p != 3q, genA at beta_d, sigA, hD, hE (rational values), Pval as an explicit
product of linear factors in dvar, and Pval*sigP as an expanded polynomial in dvar; then the
reformulated derivative term and the two branch sums.  Exact sympy arithmetic.
"""
import sys
if len(sys.argv) < 3 or any(a in ('-h', '--help') for a in sys.argv[1:]):
    print(__doc__)
    sys.exit(0)
import sympy as sp
sys.path.insert(0, '.')
from theta_check import A, d, genAIndex, odds, lam  # noqa: E402

R = sp.Rational
level = int(sys.argv[1])
out = sys.argv[2]
if level == 7:
    branches = [((2, 1), (1, 5)), ((1, 3), (4, 1))]
else:
    branches = [((1, 2), (4, 2)), ((2, 2), (1, 6))]


def q(c):
    c = R(c)
    if c.q == 1:
        return f"({c.p} : Kd)"
    return f"({c.p} / {c.q} : Kd)"


def poly_lean(expr):
    poly = sp.Poly(sp.expand(expr), d)
    terms = []
    for (k,), c in sorted(poly.terms(), reverse=True):
        terms.append(f"{q(c)} * dvar ^ {k}")
    return " + ".join(terms) if terms else "0"


def nm(a):
    return f"{a[0]}{a[1]}"


def setlit(xs):
    return "{" + ", ".join(str(x) for x in xs) + "}"


def ins_simp():
    return ("simp (config := {decide := true}) only [Finset.prod_insert, Finset.sum_insert, "
            "Finset.mem_insert, Finset.mem_singleton, Finset.prod_singleton, "
            "Finset.sum_singleton]")


lines = [
    "import Virasoro.Proofs.Sec8Jets",
    "",
    "/-!",
    f"# Explicit jets at `b₀` for the level-{level} diamond (generated by runs/theta/gen_lean.py)",
    "-/",
    "",
    "namespace Virasoro",
    "",
    "open Polynomial",
    "",
]
labels = []
for k, t in branches:
    labels += [k, t]
for a in labels:
    r, s = a
    idx = genAIndex(r, s)
    setstr = ", ".join(f"({p}, {qq})" for p, qq in idx)
    sA = sum(R(3, 4) * R(4 * p + 3 * qq, 4 * p - 3 * qq) for p, qq in idx)
    hD = R(7 - 16 * r * r + 9 * s * s, 32)
    hE = (R(1 - r * r) + R(27 * (1 - s * s), 16)) / 4
    lines += [
        f"theorem hne_{nm(a)} : ∀ pq ∈ genAIndex {r} {s}, 4 * pq.1 ≠ 3 * pq.2 := by decide",
        "",
        f"theorem genAIndex_{nm(a)} : genAIndex {r} {s} = {{{setstr}}} := by decide",
        "",
        f"theorem genAK_{nm(a)} : genA {r} {s} βd = {q(A(r, s))} := by",
        f"  rw [genA_βd_prod, show (genAIndex {r} {s}).card = {len(idx)} from by decide,",
        f"    show βd⁻¹ ^ {len(idx)} = (βd⁻¹ ^ 2) ^ {len(idx) // 2} from by ring, βd_inv_sq,",
        f"    genAIndex_{nm(a)}]",
        "  simp [Finset.prod_insert]",
        "  norm_num",
        "",
        f"theorem sigA_{nm(a)} : sigA {r} {s} = {q(sA)} := by",
        "  unfold sigA",
        f"  rw [genAIndex_{nm(a)}]",
        "  simp [Finset.sum_insert]",
        "  norm_num",
        "",
        f"theorem hD_{nm(a)} : hD ({r}, {s}) = {q(hD)} := by unfold hD; norm_num",
        "",
        f"theorem hE_{nm(a)} : hE ({r}, {s}) = {q(hE)} := by unfold hE; norm_num",
        "",
    ]
    facs = []
    for kk in odds(r):
        for ll in odds(s):
            facs.append(lam(abs(4 * kk - 3 * ll)))
            facs.append(lam(4 * kk + 3 * ll))
    pexpr = " * ".join(f"({q(c)} - dvar)" for c in facs)
    sets = (f"show oddsBelow {r} = {setlit(odds(r))} from by decide, "
            f"show oddsBelow {s} = {setlit(odds(s))} from by decide")
    if r == s:
        sets = f"show oddsBelow {r} = {setlit(odds(r))} from by decide"
    lines += [
        f"theorem Pval_{nm(a)} : Pval {r} {s} = {pexpr} := by",
        "  unfold Pval pval",
        f"  rw [{sets}]",
        f"  {ins_simp()}",
        "  push_cast",
        "  ring",
        "",
    ]
    P = 1
    for c in facs:
        P *= (c - d)
    sigP = sum(R(7 - 16 * kk * kk + 9 * ll * ll, 32) * (1 / (lam(abs(4 * kk - 3 * ll)) - d)
                                                        + 1 / (lam(4 * kk + 3 * ll) - d))
               for kk in odds(r) for ll in odds(s))
    Q = sp.cancel(sp.together(P * sigP))
    assert sp.Poly(sp.fraction(Q)[1], d).degree() == 0
    nes = []
    for kk in odds(r):
        for ll in odds(s):
            nes.append(f"  have := pval_ne {kk} {ll} 1")
            nes.append(f"  have := pval_ne {kk} {ll} (-1)")
    lines += [
        f"theorem PsigP_{nm(a)} : Pval {r} {s} * sigP {r} {s} = {poly_lean(Q)} := by",
        "  unfold Pval sigP",
        f"  rw [{sets}]",
        f"  {ins_simp()}",
    ] + nes + [
        "  field_simp",
        "  unfold pval pD",
        "  push_cast",
        "  ring",
        "",
    ]
lines += ["end Virasoro", ""]
open(out, 'w').write("\n".join(lines))
print(f"wrote {out}: {len(lines)} lines", flush=True)
