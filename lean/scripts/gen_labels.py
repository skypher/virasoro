"""Generate Virasoro/Proofs/Sec8RegLabels.lean: the eight rows of Lemma 8.4.

Usage: python3 -u gen_labels.py OUT.lean [-h|--help]
Uses the LU certificates of luB.py (recomputed here) for the matrices B_m(1/2,h).
"""
import sys
from fractions import Fraction as F
if len(sys.argv) < 2 or any(a in ('-h', '--help') for a in sys.argv[1:]):
    print(__doc__)
    sys.exit(0)
sys.path.insert(0, '/home/yang/virasoro/runs/theta')
from detB import data, labels  # noqa: E402
from luB import lu, swaps_of  # noqa: E402

H = {(2, 1): F(1, 2), (1, 3): F(1, 2), (1, 2): F(1, 16), (2, 2): F(1, 16), (1, 5): F(5, 2),
     (4, 1): F(7, 2), (4, 2): F(33, 16), (1, 6): F(65, 16)}


def q(x):
    x = F(x)
    return f"({x.numerator} / {x.denominator} : ℚ)" if x.denominator != 1 else f"({x.numerator} : ℚ)"


def qc(x):
    x = F(x)
    return f"({x.numerator} / {x.denominator} : ℂ)" if x.denominator != 1 else f"({x.numerator} : ℂ)"


def rows_lit(M):
    return "[" + ", ".join("[" + ", ".join(q(v) for v in row) + "]" for row in M) + "]"


out = ["import Virasoro.Proofs.Sec8RegCase", "",
       "/-!", "# Lemma 8.4: the eight rows (generated by `scripts/gen_labels.py`)",
       "", "The permuted LU factorizations certify the determinants; they were computed in exact",
       "arithmetic from engine output and are checked here by kernel evaluation.", "-/", "",
       "namespace Virasoro", "", "open Verma Module", "", "set_option maxRecDepth 200000", ""]
levels = sorted({lab[0] * lab[1] for lab, _ in labels})
out += ["theorem isUpper_of {n : ℕ} {rows : List (List ℚ)}",
        "    (h : ∀ i j : Fin n, j < i → (rows.getD i []).getD j (0 : ℚ) = 0) :",
        "    (matOfRows n rows).IsUpperTriangular := fun i j hij => h i j hij",
        "",
        "theorem isLower_of {n : ℕ} {rows : List (List ℚ)}",
        "    (h : ∀ i j : Fin n, i < j → (rows.getD i []).getD j (0 : ℚ) = 0) :",
        "    (matOfRows n rows).IsLowerTriangular := fun i j hij => h i j hij",
        "",
        "theorem diag_of {n : ℕ} {rows : List (List ℚ)}",
        "    (h : ∀ i : Fin n, (rows.getD i []).getD i (0 : ℚ) = 1) : ∀ i, matOfRows n rows i i = 1 := h",
        "",
        "theorem prod_diag_of {n : ℕ} (rows : List (List ℚ)) :",
        "    ∏ i, matOfRows n rows i i = ∏ i : Fin n, (rows.getD i []).getD i (0 : ℚ) := rfl",
        ""]
for m in levels:
    out += [f"theorem lexLen_pos_{m} : 0 < (lexWords {m}).length := by decide +kernel", ""]
    out += [f"theorem levelData_{m} : LevelData {m} where",
            f"  em := isEnum_lexWords {m} (by decide +kernel) (by unfold PosWord; decide +kernel) (by decide +kernel)",
            f"  e1 := isEnum_lexWords ({m} - 1) (by decide +kernel) (by unfold PosWord; decide +kernel) (by decide +kernel)",
            f"  e2 := isEnum_lexWords ({m} - 2) (by decide +kernel) (by unfold PosWord; decide +kernel) (by decide +kernel)",
            "  t1 := by decide +kernel", "  t2 := by decide +kernel",
            "  rows := by decide +kernel", "  pos := by decide +kernel", ""]
for (lab, D), B in zip(labels, data):
    r, s = lab
    m = r * s
    hq = H[lab]
    perm, Lm, U = lu(B)
    sw = swaps_of(perm)
    nm = f"{r}{s}"
    n = len(B)
    out += [f"def swaps_{nm} : List (ℕ × ℕ) := {[(a, b) for a, b in sw]}",
            f"def Lrows_{nm} : List (List ℚ) := {rows_lit(Lm)}",
            f"def Urows_{nm} : List (List ℚ) := {rows_lit(U)}",
            "",
            f"theorem detB_{nm} : (Bmat {m} (1 / 2 : ℚ) {q(hq)}).det = {q(D)} := by",
            f"  rw [det_of_PLU (swapPerm _ lexLen_pos_{m} swaps_{nm}) (L := matOfRows _ Lrows_{nm})",
            f"    (U := matOfRows _ Urows_{nm}) (by decide +kernel)",
            "    (isLower_of (by decide +kernel))",
            "    (diag_of (by decide +kernel))",
            "    (isUpper_of (by decide +kernel)),",
            f"    sign_swapPerm _ lexLen_pos_{m} swaps_{nm} (by decide +kernel), prod_diag_of]",
            "  decide +kernel",
            "",
            f"theorem regularCase_{nm} (hH : Cited_HJSNormalizations) :",
            f"    RegularCase {r} {s} {qc(hq)} {qc(D)} :=",
            f"  regularCase_of hH {r} {s} (by norm_num) (by norm_num) {q(hq)} {q(D)} {qc(hq)} {qc(D)}",
            "    (by rw [def_fixed_specialization_ising.2]; norm_num [isingDelta])",
            "    (by simp [map_div₀]) (by simp [map_div₀]) (by norm_num)",
            f"    levelData_{m} detB_{nm}", ""]
    print(lab, 'n', n, 'swaps', len(sw), flush=True)
out += ["/-- Lemma 8.4 (`lem:regular-families`).", "",
        "Paper label: lem:regular-families -/",
        "theorem lem_regular_families (hH : Cited_HJSNormalizations) : Stmt_lem_regular_families :=",
        "  ⟨regularCase_21 hH, regularCase_13 hH, regularCase_12 hH, regularCase_22 hH,",
        "    regularCase_15 hH, regularCase_41 hH, regularCase_42 hH, regularCase_16 hH⟩", "",
        "end Virasoro", ""]
open(sys.argv[1], 'w').write("\n".join(out))
print('wrote', sys.argv[1], flush=True)
